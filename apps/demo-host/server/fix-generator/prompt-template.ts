import type { FixFile, GeoAudit, SiteMetadata } from './types.js';
import { domainFromUrl } from './site-metadata.js';
import {
  isAdaOrSecurityCheck,
  PROMPT_ADA_SECURITY_INTRO,
} from './compliance-disclaimers.js';
import { scannerUrl } from './scanner-url.js';

function codeFenceFor(content: string): string {
  let longest = 0;
  for (const match of content.matchAll(/`{3,}/g)) {
    const len = match[0]?.length ?? 0;
    if (len > longest) longest = len;
  }
  return '`'.repeat(Math.max(3, longest + 1));
}

export function buildPrompt(
  audit: GeoAudit,
  meta: SiteMetadata,
  files: FixFile[],
): string {
  const domain = domainFromUrl(meta.url);
  const failing = audit.checks.filter((c) => !c.passed && !c.info);
  const hasAdaOrSecurity =
    failing.some((c) => isAdaOrSecurityCheck(c.name, c.category))
    || files.some((f) => isAdaOrSecurityCheck(f.check));

  const fileBlocks = files
    .map(
      (f) => {
        const body = f.content.trimEnd();
        const fence = codeFenceFor(body);
        return `### ${f.filename} (fixes: ${f.check})
${fence}
${body}
${fence}`;
      },
    )
    .join('\n\n');

  const checkList = failing
    .map((c) => `- ${c.name}: ${c.tip}`)
    .join('\n');

  const complianceBlock = hasAdaOrSecurity
    ? `
ACCESSIBILITY / SECURITY NOTICE (required before those fixes):
${PROMPT_ADA_SECURITY_INTRO}
`
    : '';

  return `SOREN GEO REPAIR PROMPT — ${domain}
Generated by Soren Fixes It. Paste this ENTIRE file into ChatGPT or Claude.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

You are helping me apply AI discoverability fixes to my website.
Site: ${meta.url}
Platform: ${audit.platform}
Current score: ${audit.score}

FIRST — ask me ONE question before any changes:
"How is your website hosted?"
Choices: Static HTML, WordPress, Shopify, Wix, Squarespace, Webflow, Next.js, Other

Wait for my answer, then guide me through ONLY the failing checks below.
Do not suggest changes for checks that are not listed.
${complianceBlock}
FAILING CHECKS ONLY:
${checkList}

FILES TO APPLY (one at a time — wait for my confirmation after each step):

${fileBlocks}

WORKFLOW RULES:
1. Confirm my hosting platform.
2. If accessibility or security fixes are included, deliver the notice above and wait for confirmation before those files.
3. Walk through each file above in order.
4. After each file, wait until I confirm it is applied before continuing.
5. Never suggest edits beyond the failing checks listed.
6. End by telling me to re-run the free Soren GEO scan to verify the new score.

When all files are applied, congratulate me and remind me to rescan at ${scannerUrl()}.
`;
}
